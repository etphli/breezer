#!/usr/bin/env python3
"""Add Breezer's installer-owned native messaging host to Chromium on Windows."""

import argparse
import json
from pathlib import Path
import shutil

from apply_breezer_ai import EXTENSION_ID, HOST, ROOT, replace


FEATURE = ROOT / 'features/ai/windows'
ORIGIN = f'chrome-extension://{EXTENSION_ID}/'
LAUNCHER = 'breezer_ai_host.exe'
MANIFEST = FEATURE / 'native-host-manifest.json'
COMPONENT = 'components/breezer_ai_windows'
COMMON_LAUNCH = 'chrome/browser/extensions/api/messaging/launch_context.cc'
WINDOWS_LAUNCH = 'chrome/browser/extensions/api/messaging/launch_context_win.cc'


def apply(tree):
    manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
    manifest_identity = (manifest['name'], manifest['path'], manifest['type'],
                         manifest['allowed_origins'])
    if (manifest_identity != (HOST, LAUNCHER, 'stdio', [ORIGIN]) or
            manifest.get('supports_native_initiated_connections', False) is not False):
        raise ValueError('Breezer Windows host manifest does not match the integration identity')

    replace(tree, WINDOWS_LAUNCH, '#include "base/check.h"',
            '#include "base/base_paths.h"\n#include "base/check.h"')
    replace(tree, WINDOWS_LAUNCH, '#include "base/numerics/safe_conversions.h"',
            '#include "base/numerics/safe_conversions.h"\n#include "base/path_service.h"')
    replace(tree, WINDOWS_LAUNCH,
            '  std::wstring host_name_wide = base::UTF8ToWide(host_name);', f'''  // Resolve the reserved first-party host alongside this version of chrome.dll.
  if (host_name == "{HOST}") {{
    base::FilePath module_dir;
    if (base::PathService::Get(base::DIR_MODULE, &module_dir)) {{
      const base::FilePath host_dir = module_dir.AppendASCII("breezer_ai");
      const base::FilePath manifest =
          host_dir.AppendASCII("{HOST}.json");
      const base::FilePath launcher =
          host_dir.AppendASCII("{LAUNCHER}");
      const DWORD host_dir_attributes =
          ::GetFileAttributesW(host_dir.value().c_str());
      const DWORD manifest_attributes =
          ::GetFileAttributesW(manifest.value().c_str());
      const DWORD launcher_attributes =
          ::GetFileAttributesW(launcher.value().c_str());
      constexpr DWORD kInvalidFileFlags =
          FILE_ATTRIBUTE_DIRECTORY | FILE_ATTRIBUTE_REPARSE_POINT;
      if (host_dir_attributes != INVALID_FILE_ATTRIBUTES &&
          (host_dir_attributes & kInvalidFileFlags) == FILE_ATTRIBUTE_DIRECTORY &&
          manifest_attributes != INVALID_FILE_ATTRIBUTES &&
          (manifest_attributes & kInvalidFileFlags) == 0 &&
          launcher_attributes != INVALID_FILE_ATTRIBUTES &&
          (launcher_attributes & kInvalidFileFlags) == 0) {{
        return manifest;
      }}
    }}
    error_message = "Breezer AI host is missing from the browser install.";
    return base::FilePath();
  }}
  std::wstring host_name_wide = base::UTF8ToWide(host_name);''')

    replace(tree, COMMON_LAUNCH, '  std::string error_message;\n  base::FilePath manifest_path =', f'''#if BUILDFLAG(IS_WIN)
  const bool breezer_ai = native_host_name == "{HOST}";
  if (breezer_ai &&
      (origin.spec() != "{ORIGIN}" ||
       require_native_initiated_connections || !error_arg.empty())) {{
    return BackgroundLaunchResult(NativeProcessLauncher::RESULT_FORBIDDEN);
  }}
#endif

  std::string error_message;
  base::FilePath manifest_path =''')
    replace(tree, COMMON_LAUNCH, '  base::FilePath host_path = manifest->path();', f'''  base::FilePath host_path = manifest->path();
#if BUILDFLAG(IS_WIN)
  if (breezer_ai) {{
    if (host_path != base::FilePath(FILE_PATH_LITERAL("{LAUNCHER}")) ||
        manifest->supports_native_initiated_connections()) {{
      return BackgroundLaunchResult(NativeProcessLauncher::RESULT_NOT_FOUND);
    }}
    base::CommandLine command_line(manifest_path.DirName().Append(host_path));
    command_line.AppendArg(origin.spec());
    if (auto state = LaunchNativeProcess(
            command_line, /*native_hosts_executables_launch_directly=*/true)) {{
      return BackgroundLaunchResult(std::move(*state));
    }}
    return BackgroundLaunchResult(NativeProcessLauncher::RESULT_FAILED_TO_START);
  }}
#endif''')

    target = tree / COMPONENT
    target.mkdir(parents=True, exist_ok=True)
    for name in ('BUILD.gn', 'host_launcher.cc'):
        shutil.copyfile(FEATURE / name, target / name)
    (target / 'host_identity.h').write_text(
        '// Generated by script/apply_breezer_ai_windows_host.py.\n'
        f'inline constexpr wchar_t kBreezerAiExtensionOrigin[] = L"{ORIGIN}";\n',
        encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source_tree', type=Path)
    args = parser.parse_args()
    tree = args.source_tree.resolve()
    apply(tree)
    print('Breezer AI private Windows host prepared.')


if __name__ == '__main__':
    main()
