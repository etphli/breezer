#!/usr/bin/env python3
"""Install Breezer AI into a prepared, patched Chromium source tree."""

import argparse
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parent.parent
IDENTITY = json.loads((ROOT / 'features/ai/integration/identity.json').read_text())
EXTENSION_ID = IDENTITY['extension_id']
HOST = IDENTITY['native_host']

# Only these upstream files are changed. Resource files live under components/.
PATCHED_FILES = (
    'chrome/browser/extensions/component_loader.h',
    'chrome/browser/extensions/component_loader.cc',
    'chrome/browser/extensions/component_extensions_allowlist/allowlist.cc',
    'chrome/browser/extensions/chrome_component_extension_resource_manager.cc',
    'chrome/browser/extensions/BUILD.gn',
    'chrome/chrome_paks.gni',
    'tools/gritsettings/resource_ids.spec',
    'chrome/app/chrome_command_ids.h',
    'chrome/app/generated_resources.grd',
    'chrome/browser/ui/browser_shortcuts/browser_shortcut_metadata.cc',
    'chrome/browser/ui/browser_command_controller.cc',
    'chrome/browser/global_keyboard_shortcuts_mac.mm',
    'chrome/browser/ui/cocoa/accelerators_cocoa.mm',
    'chrome/browser/ui/views/frame/browser_native_widget_mac.mm',
    'chrome/browser/extensions/api/messaging/launch_context_posix.cc',
    'chrome/browser/extensions/api/messaging/launch_context.cc',
)


def replace(tree, path, before, after):
    target = tree / path
    text = target.read_text()
    if after in text:
        return
    if text.count(before) != 1:
        raise ValueError(f'Breezer AI anchor changed in {path}: {before!r}')
    target.write_text(text.replace(before, after, 1))


def resources(tree):
    source = ROOT / 'features/ai/extension'
    manifest = json.loads((source / 'manifest.json').read_text())
    if manifest.get('key') != IDENTITY['public_key']:
        raise ValueError('Breezer AI manifest key does not match integration identity')
    target = tree / 'components/breezer_ai'
    target.mkdir(parents=True, exist_ok=True)
    files = sorted(p.relative_to(source).as_posix() for p in source.rglob('*') if p.is_file())
    if len(files) > 20:
        raise ValueError('Breezer AI resources exceed the reserved GRIT allocation')
    for file in files:
        destination = target / file
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source / file, destination)
    inputs = '\n'.join(f'    "{file}",' for file in files)
    (target / 'BUILD.gn').write_text('''# Generated by script/apply_breezer_ai.py.
import("//ui/webui/resources/tools/generate_grd.gni")
import("//tools/grit/grit_rule.gni")

generated_grd = "$target_gen_dir/resources.grd"
generate_grd("breezer_ai_grd") {
  out_grd = generated_grd
  grd_prefix = "breezer_ai"
  resource_path_prefix = "breezer_ai"
  input_files_base_dir = rebase_path(".", "//")
  input_files = [
''' + inputs + '''
  ]
}
grit("breezer_ai") {
  source = generated_grd
  enable_input_discovery_for_gn_analyze = false
  output_dir = "$target_gen_dir/resources"
  outputs = [
    "grit/breezer_ai_resources.h",
    "grit/breezer_ai_resources_map.cc",
    "grit/breezer_ai_resources_map.h",
    "breezer_ai_resources.pak",
  ]
  deps = [ ":breezer_ai_grd" ]
}
''')


def apply(tree):
    r = lambda path, before, after: replace(tree, path, before, after)
    r('chrome/browser/extensions/component_loader.h',
      '  void AddExtstoreFixups();', '  void AddExtstoreFixups();\n  void AddBreezerAi();')
    r('chrome/browser/extensions/component_loader.cc',
      '#include "components/extstore_fixups/resources/grit/extstore_fixups_resources.h"',
      '#include "components/extstore_fixups/resources/grit/extstore_fixups_resources.h"\n#include "components/breezer_ai/resources/grit/breezer_ai_resources.h"')
    r('chrome/browser/extensions/component_loader.cc',
      'void ComponentLoader::AddExtstoreFixups() {',
      'void ComponentLoader::AddBreezerAi() {\n  Add(IDR_BREEZER_AI_MANIFEST_JSON,\n      base::FilePath(FILE_PATH_LITERAL("breezer_ai")));\n}\n\nvoid ComponentLoader::AddExtstoreFixups() {')
    r('chrome/browser/extensions/component_loader.cc',
      '    AddExtstoreFixups();', '    AddExtstoreFixups();\n    AddBreezerAi();')
    r('chrome/browser/extensions/component_extensions_allowlist/allowlist.cc',
      '#include "components/extstore_fixups/extension_ids.h"',
      '#include "components/breezer_ai/resources/grit/breezer_ai_resources.h"\n#include "components/extstore_fixups/extension_ids.h"')
    r('chrome/browser/extensions/component_extensions_allowlist/allowlist.cc',
      '      helium::kExtstoreFixupsExtensionId,',
      f'      helium::kExtstoreFixupsExtensionId,\n      "{EXTENSION_ID}",  // Breezer AI')
    r('chrome/browser/extensions/component_extensions_allowlist/allowlist.cc',
      '    case IDR_EXTSTORE_FIXUPS_MANIFEST_JSON:',
      '    case IDR_EXTSTORE_FIXUPS_MANIFEST_JSON:\n    case IDR_BREEZER_AI_MANIFEST_JSON:')
    r('chrome/browser/extensions/chrome_component_extension_resource_manager.cc',
      '#include "components/extstore_fixups/resources/grit/extstore_fixups_resources_map.h"',
      '#include "components/extstore_fixups/resources/grit/extstore_fixups_resources_map.h"\n#include "components/breezer_ai/resources/grit/breezer_ai_resources_map.h"')
    r('chrome/browser/extensions/chrome_component_extension_resource_manager.cc',
      '  AddComponentResourceEntries(kExtstoreFixupsResources);',
      '  AddComponentResourceEntries(kExtstoreFixupsResources);\n  AddComponentResourceEntries(kBreezerAiResources);')
    r('chrome/browser/extensions/BUILD.gn', '    "//components/extstore_fixups",',
      '    "//components/extstore_fixups",\n    "//components/breezer_ai",')
    r('chrome/chrome_paks.gni',
      '      "$root_gen_dir/components/extstore_fixups/resources/extstore_fixups_resources.pak",',
      '      "$root_gen_dir/components/extstore_fixups/resources/extstore_fixups_resources.pak",\n      "$root_gen_dir/components/breezer_ai/resources/breezer_ai_resources.pak",')
    r('chrome/chrome_paks.gni', '      "//components/extstore_fixups",',
      '      "//components/extstore_fixups",\n      "//components/breezer_ai",')
    # Like Helium's extstore resources, use an unused ChromeOS allocation on macOS.
    r('tools/gritsettings/resource_ids.spec',
      '"<(SHARED_INTERMEDIATE_DIR)/chrome/browser/resources/ash/extended_updates/resources.grd"',
      '"<(SHARED_INTERMEDIATE_DIR)/components/breezer_ai/resources.grd"')
    r('chrome/app/chrome_command_ids.h',
      '#endif  // CHROME_APP_CHROME_COMMAND_IDS_H_',
      '#define IDC_TOGGLE_BREEZER_AI 34092\n\n#endif  // CHROME_APP_CHROME_COMMAND_IDS_H_')
    r('chrome/app/generated_resources.grd', '</messages>',
      '<message name="IDS_BREEZER_AI" desc="Label for the Breezer AI side panel shortcut">Breezer AI</message>\n  </messages>')
    r('chrome/browser/ui/browser_shortcuts/browser_shortcut_metadata.cc',
      '    case IDC_FOCUS_SEARCH:',
      '    case IDC_TOGGLE_BREEZER_AI:\n      return Label(IDS_BREEZER_AI);\n    case IDC_FOCUS_SEARCH:')
    r('chrome/browser/global_keyboard_shortcuts_mac.mm',
      '      {true,  true,  false, false, kVK_ANSI_RightBracket, IDC_SELECT_NEXT_TAB},',
      '      {true,  false, false, false, kVK_ANSI_K,            IDC_TOGGLE_BREEZER_AI},\n      {true,  true,  false, false, kVK_ANSI_RightBracket, IDC_SELECT_NEXT_TAB},')
    r('chrome/browser/ui/cocoa/accelerators_cocoa.mm',
      '    {IDC_FOCUS_SEARCH, ui::EF_COMMAND_DOWN | ui::EF_ALT_DOWN, ui::VKEY_F},',
      '    {IDC_FOCUS_SEARCH, ui::EF_COMMAND_DOWN | ui::EF_ALT_DOWN, ui::VKEY_F},\n    {IDC_TOGGLE_BREEZER_AI, ui::EF_COMMAND_DOWN, ui::VKEY_K},')
    r('chrome/browser/ui/views/frame/browser_native_widget_mac.mm',
      '    case IDC_PRINT:', '    case IDC_TOGGLE_BREEZER_AI:\n    case IDC_PRINT:')
    r('chrome/browser/ui/browser_command_controller.cc',
      '#include "extensions/browser/extension_registry.h"',
      '#include "extensions/browser/extension_registry.h"\n#include "extensions/browser/permissions/active_tab_permission_granter.h"')
    r('chrome/browser/ui/browser_command_controller.cc',
      '    case IDC_FOCUS_SEARCH:', f'''    case IDC_TOGGLE_BREEZER_AI: {{
      if (profile()->IsOffTheRecord()) {{
        break;
      }}
      const auto* extension = ExtensionRegistry::Get(profile())
                                  ->enabled_extensions().GetByID(
                                      "{EXTENSION_ID}");
      auto* contents = browser_->tab_strip_model()->GetActiveWebContents();
      if (extension && contents) {{
        if (auto* granter = extensions::ActiveTabPermissionGranter::FromWebContents(contents)) {{
          granter->GrantIfRequested(extension);
        }}
        if (auto* side_panel = SidePanelUI::From(browser_)) {{
          side_panel->Toggle(
              SidePanelEntryKey(SidePanelEntryId::kExtension,
                                "{EXTENSION_ID}"),
              SidePanelOpenTrigger::kExtension);
        }}
      }}
      break;
    }}
    case IDC_FOCUS_SEARCH:''')
    r('chrome/browser/ui/browser_command_controller.cc',
      '  command_updater_->UpdateCommandEnabled(IDC_FOCUS_SEARCH, show_main_ui);',
      '  command_updater_->UpdateCommandEnabled(IDC_FOCUS_SEARCH, show_main_ui);\n  command_updater_->UpdateCommandEnabled(\n      IDC_TOGGLE_BREEZER_AI, show_main_ui && !profile()->IsOffTheRecord());')
    r('chrome/browser/extensions/api/messaging/launch_context_posix.cc',
      '  base::FilePath result;\n  if (allow_user_level_hosts) {', f'''  base::FilePath result;
#if BUILDFLAG(IS_MAC)
  // The first-party host is resolved only inside this application bundle.
  // Never permit a user-level manifest to replace it.
  if (host_name == "{HOST}") {{
    base::FilePath resources;
    if (base::PathService::Get(chrome::DIR_RESOURCES, &resources)) {{
      result = resources.AppendASCII("breezer_ai")
                   .AppendASCII("{HOST}.json");
      if (base::PathExists(result)) {{
        return result;
      }}
    }}
    error_message = "Breezer AI host is missing from the application bundle";
    return base::FilePath();
  }}
#endif
  if (allow_user_level_hosts) {{''')
    r('chrome/browser/extensions/api/messaging/launch_context.cc',
      '#include "chrome/common/chrome_features.h"',
      '#include "chrome/common/chrome_features.h"\n#include "chrome/common/chrome_paths.h"')
    r('chrome/browser/extensions/api/messaging/launch_context.cc',
      '  base::FilePath host_path = manifest->path();', f'''  base::FilePath host_path = manifest->path();
#if BUILDFLAG(IS_MAC)
  if (native_host_name == "{HOST}") {{
    base::FilePath resources;
    if (!base::PathService::Get(chrome::DIR_RESOURCES, &resources) ||
        manifest_path != resources.AppendASCII("breezer_ai")
                             .AppendASCII("{HOST}.json") ||
        host_path != base::FilePath(FILE_PATH_LITERAL("host/launch.sh"))) {{
      return BackgroundLaunchResult(NativeProcessLauncher::RESULT_NOT_FOUND);
    }}
    host_path = manifest_path.DirName().Append(host_path);
  }}
#endif''')
    resources(tree)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source_tree', type=Path)
    args = parser.parse_args()
    tree = args.source_tree.resolve()
    if not (tree / 'chrome/browser/extensions/component_loader.cc').is_file():
        parser.error('Use the prepared Chromium source tree after upstream patches.')
    apply(tree)
    print('Breezer AI component, native side panel shortcut, and private host lookup prepared.')


if __name__ == '__main__':
    main()
